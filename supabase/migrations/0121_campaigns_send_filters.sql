-- 발송 조건(crm_campaigns.send_filters) 스냅샷 저장.
-- ------------------------------------------------------------
-- 배경 (2026-08-11):
--   2026-08-10 '손나래T 영동고2 영어' 발송이 큐 적재 전에 실패해 crm_messages 가
--   0건으로 남았다. "실패 건 재발송" 은 실패 *메시지 행* 을 다시 보내는 기능이라
--   재발송할 대상이 없고, 캠페인 행에도 "누구에게 보내려던 건지"(필터 조건)가
--   저장돼 있지 않아 원클릭 재발송이 불가능했다. 결국 운영자가 학교·학년 조건을
--   기억해 손으로 다시 골라야 했다.
--
-- 정책:
--   - 필터 기반(/compose) · 그룹 기반 발송은 해석된 GroupFilters 를 그대로 저장한다.
--     (그룹 기반도 발송 시점 스냅샷을 남긴다 — 그룹이 나중에 수정돼도 재현 가능)
--   - 엑셀 발송·설명회 발송은 NULL. 엑셀은 업로드 파일이, 설명회는 invitation 이
--     대상의 원천이라 필터로 재현되지 않는다.
--   - 이 값으로 "같은 조건으로 다시 보내기" 가 동작한다. 재발송은 기존 캠페인을
--     수정하지 않고 **새 캠페인**을 만든다(발송 이력 보존).
--   - 스냅샷일 뿐 재조회 시점의 학생 명단은 달라질 수 있다(전학·수신거부 등).
--     읽는 쪽에서 GroupFiltersSchema 로 Zod 재검증한다.
-- ============================================================

ALTER TABLE public.crm_campaigns
  ADD COLUMN IF NOT EXISTS send_filters JSONB;

COMMENT ON COLUMN public.crm_campaigns.send_filters IS
  '발송 대상 조건(GroupFilters) 스냅샷. 필터·그룹 기반 발송만 채워지고 엑셀·설명회 발송은 NULL. "같은 조건으로 다시 보내기"(새 캠페인 생성)와 발송 대상 감사 추적에 쓴다. 발송 시점 조건일 뿐 학생 명단은 재조회 시점 기준으로 달라질 수 있다. 0121 추가.';
